function shortenTopicForTitle(topic: string): string {
  const clean = topic.replace(/[«»"']/g, '').trim();
  if (clean.length <= 38) return clean;
  const words = clean.split(/\s+/);
  let acc = '';
  for (const w of words) {
    if ((acc + ' ' + w).trim().length > 36) break;
    acc = (acc + ' ' + w).trim();
  }
  return acc ? `${acc}…` : clean.slice(0, 36);
}

